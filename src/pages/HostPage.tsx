  const expirationDate = getExpirationDate(details?.expiresAt);

  const isExpired =
    !isPro && expirationDate !== null && expirationDate.getTime() <= Date.now();

  const canStart = !!group && isInactive && !isExpired && questions.length > 0;

  const canFinish = !!group && isActive;

  const [copied, setCopied] = useState(false);
  const [busy, setBusy] = useState<ActionType | null>(null);
  const [showStartModal, setShowStartModal] = useState(false);
  const [showFinishModal, setShowFinishModal] = useState(false);

