function getExpirationDate(expiresAt?: GroupExtras["expiresAt"]): Date | null {
  if (!expiresAt) return null;

  const date =
    typeof expiresAt === "object" &&
    "toDate" in expiresAt &&
    typeof expiresAt.toDate === "function"
      ? expiresAt.toDate()
      : new Date(expiresAt as string | Date);

  return Number.isNaN(date.getTime()) ? null : date;
}

function getDaysLeft(expiresAt?: GroupExtras["expiresAt"]): number | null {
  const date = getExpirationDate(expiresAt);

  if (!date) return null;

  return Math.max(0, Math.ceil((date.getTime() - Date.now()) / 86_400_000));
}

async function copyToClipboard(value: string) {
  if (navigator.clipboard?.writeText) {
    try {
      await navigator.clipboard.writeText(value);
      return;
    } catch {
      // Tenta o método alternativo.
    }
  }

  const textarea = document.createElement("textarea");
  textarea.value = value;
  textarea.style.position = "fixed";
  textarea.style.opacity = "0";

  document.body.appendChild(textarea);
  textarea.select();

  const success = document.execCommand("copy");

  document.body.removeChild(textarea);

  if (!success) {
    throw new Error("Clipboard unavailable");
  }
}

function HighlightedModalTitle({
  title,
  highlight,
  color,
}: {
  title: string;
  highlight: string;
  color: string;
}) {
  const index = title.indexOf(highlight);

  if (index === -1) return <>{title}</>;

  return (
    <>
      {title.slice(0, index)}
      <span className={color}>{highlight}</span>
      {title.slice(index + highlight.length)}
    </>
  );
}

