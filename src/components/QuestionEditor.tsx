import {
  collection,
  deleteDoc,
  doc,
  getDoc,
  runTransaction,
} from "firebase/firestore";
import { db } from "../lib/firebase";
import { useMemo, useState } from "react";
import { useTranslation } from "react-i18next";
import {
  Trash2,
  PlusCircle,
  LockKeyhole,
  CheckCircle2,
  Loader2,
} from "lucide-react";
import { FREE_QUESTION_LIMIT } from "../config/limits";

type Question = {
  id: string;
  index: number;
  text: string;
  options: string[];
  correctIndex: number;
};

type QuestionEditorProps = {
  groupId: string;
  questions: Question[];
  isPro: boolean;
  status: string;
  isAiGenerated?: boolean;
};

const translations = {
  pt: {
    lockedTitle: "Perguntas bloqueadas",
    lockedDescription:
      "Este quiz já foi iniciado ou finalizado. As perguntas estão disponíveis apenas para consulta.",
    aiTitle: "Quiz gerado pela Nyxie",
    aiDescription:
      "As perguntas geradas por inteligência artificial não podem ser modificadas.",
    draftTitle: "Preparando seu quiz",
    draftDescription:
      "Adicione e revise suas perguntas antes de iniciar a partida.",
    correctAnswer: "Resposta correta",
    saving: "Salvando...",
    removing: "Removendo...",
    error: "Não foi possível realizar a operação. Tente novamente.",
    statusChanged:
      "Este quiz não está mais disponível para edição. Atualize a página.",
    removeConfirm: "Deseja remover esta pergunta?",
  },
  en: {
    lockedTitle: "Questions locked",
    lockedDescription:
      "This quiz has already started or finished. Questions are available for viewing only.",
    aiTitle: "Quiz generated by Nyxie",
    aiDescription: "AI-generated questions cannot be modified.",
    draftTitle: "Preparing your quiz",
    draftDescription:
      "Add and review your questions before starting the session.",
    correctAnswer: "Correct answer",
    saving: "Saving...",
    removing: "Removing...",
    error: "Unable to complete this operation. Please try again.",
    statusChanged: "This quiz is no longer editable. Refresh the page.",
    removeConfirm: "Do you want to remove this question?",
  },
  es: {
    lockedTitle: "Preguntas bloqueadas",
    lockedDescription:
      "Este quiz ya comenzó o finalizó. Las preguntas solo están disponibles para consulta.",
    aiTitle: "Quiz generado por Nyxie",
    aiDescription:
      "Las preguntas generadas por inteligencia artificial no se pueden modificar.",
    draftTitle: "Preparando tu quiz",
    draftDescription:
      "Agrega y revisa tus preguntas antes de comenzar la partida.",
    correctAnswer: "Respuesta correcta",
    saving: "Guardando...",
    removing: "Eliminando...",
    error: "No se pudo completar la operación. Inténtalo de nuevo.",
    statusChanged: "Este quiz ya no se puede editar. Actualiza la página.",
    removeConfirm: "¿Deseas eliminar esta pregunta?",
  },
};

export default function QuestionEditor({
  groupId,
  questions,
  isPro,
  status,
  isAiGenerated = false,
}: QuestionEditorProps) {
  const { t, i18n } = useTranslation();

  const language = (i18n.resolvedLanguage || i18n.language || "en").split(
    "-",
  )[0] as keyof typeof translations;

  const copy = translations[language] || translations.en;

  const [text, setText] = useState("");
  const [opts, setOpts] = useState(["", "", "", ""]);
  const [correctIndex, setCorrectIndex] = useState(0);
  const [busy, setBusy] = useState<string | null>(null);

  const isDraft = status === "draft" || status === "";
  const canEdit = isDraft && !isAiGenerated;

  const isFreeLimitReached = useMemo(
    () => !isPro && questions.length >= FREE_QUESTION_LIMIT,
    [isPro, questions.length],
  );

  const sortedQuestions = useMemo(
    () => [...questions].sort((a, b) => (a.index ?? 0) - (b.index ?? 0)),
    [questions],
  );

  async function add() {
    if (!canEdit || busy) return;

    if (!text.trim() || opts.some((option) => !option.trim())) {
      alert(t("editor.validation.incomplete"));
      return;
    }

    if (isFreeLimitReached) {
      alert(
        t("editor.limit.freeReached", {
          limit: FREE_QUESTION_LIMIT,
        }),
      );
      return;
    }

    setBusy("add");

    try {
      const groupRef = doc(db, "groups", groupId);
      const questionRef = doc(collection(db, "groups", groupId, "questions"));

      await runTransaction(db, async (transaction) => {
        const groupSnapshot = await transaction.get(groupRef);

        if (!groupSnapshot.exists()) {
          throw new Error("GROUP_NOT_FOUND");
        }

        const currentStatus = groupSnapshot.data().status ?? "";

        if (currentStatus !== "draft" && currentStatus !== "") {
          throw new Error("QUIZ_LOCKED");
        }

        transaction.set(questionRef, {
          text: text.trim(),
          options: opts.map((option) => option.trim()),
          correctIndex,
          index: questions.length,
        });
      });

      setText("");
      setOpts(["", "", "", ""]);
      setCorrectIndex(0);
    } catch (error) {
      console.error("Error adding question:", error);

      alert(
        error instanceof Error && error.message === "QUIZ_LOCKED"
          ? copy.statusChanged
          : copy.error,
      );
    } finally {
      setBusy(null);
    }
  }

  async function remove(id: string) {
    if (!canEdit || busy) return;

    if (!window.confirm(copy.removeConfirm)) return;

    setBusy(id);

    try {
      const groupRef = doc(db, "groups", groupId);
      const questionRef = doc(db, "groups", groupId, "questions", id);

      await runTransaction(db, async (transaction) => {
        const groupSnapshot = await transaction.get(groupRef);

        if (!groupSnapshot.exists()) {
          throw new Error("GROUP_NOT_FOUND");
        }

        const currentStatus = groupSnapshot.data().status ?? "";

        if (currentStatus !== "draft" && currentStatus !== "") {
          throw new Error("QUIZ_LOCKED");
        }

        transaction.delete(questionRef);
      });
    } catch (error) {
      console.error("Error removing question:", error);

      alert(
        error instanceof Error && error.message === "QUIZ_LOCKED"
          ? copy.statusChanged
          : copy.error,
      );
    } finally {
      setBusy(null);
    }
  }

  return (
    <section className="space-y-5 rounded-2xl border border-white/10 bg-[#0b1529]/85 p-5 shadow-xl backdrop-blur-sm sm:p-6">
      {/* Header */}
      <div className="flex flex-wrap items-start justify-between gap-4">
        <div>
          <h3 className="text-xl font-bold text-white">{t("editor.title")}</h3>

          <p className="mt-1 text-sm text-slate-400">
            {t("editor.subtitle", {
              count: questions.length,
            })}
          </p>
        </div>

        <div
          className={`flex items-center gap-2 rounded-full border px-3 py-1.5 text-xs font-semibold ${
            canEdit
              ? "border-emerald-400/30 bg-emerald-400/10 text-emerald-300"
              : "border-amber-400/30 bg-amber-400/10 text-amber-200"
          }`}
        >
          {canEdit ? <CheckCircle2 size={14} /> : <LockKeyhole size={14} />}

          {canEdit ? copy.draftTitle : copy.lockedTitle}
        </div>
      </div>

      {/* Aviso de bloqueio */}
      {!canEdit && (
        <div className="flex gap-3 rounded-xl border border-amber-400/20 bg-amber-400/5 p-4">
          <div className="flex h-10 w-10 shrink-0 items-center justify-center rounded-xl bg-amber-400/10 text-amber-300">
            <LockKeyhole size={20} />
          </div>

          <div>
            <h4 className="font-semibold text-amber-100">
              {isAiGenerated ? copy.aiTitle : copy.lockedTitle}
            </h4>

            <p className="mt-1 text-sm leading-relaxed text-slate-300">
              {isAiGenerated ? copy.aiDescription : copy.lockedDescription}
            </p>
          </div>
        </div>
      )}

      {/* Formulário: apenas quiz manual ainda não iniciado */}
      {canEdit && (
        <div className="space-y-4 rounded-xl border border-cyan-400/15 bg-[#101e35]/70 p-4 sm:p-5">
          <div className="mb-2">
            <h4 className="font-semibold text-white">{copy.draftTitle}</h4>

            <p className="mt-1 text-sm text-slate-400">
              {copy.draftDescription}
            </p>
          </div>

          <input
            className="w-full rounded-lg border border-slate-700 bg-slate-900 px-3 py-3 text-slate-100 placeholder:text-slate-500 outline-none transition focus:border-emerald-400 focus:ring-2 focus:ring-emerald-400/20"
            placeholder={t("editor.placeholder.question")}
            value={text}
            onChange={(event) => setText(event.target.value)}
            disabled={!!busy}
          />

          <div className="grid gap-3">
            {opts.map((value, index) => (
              <div key={index} className="relative overflow-hidden rounded-lg">
                <input
                  className={`w-full rounded-lg border bg-slate-900 px-3 py-3 pr-28 text-slate-100 placeholder:text-slate-500 outline-none transition focus:ring-2 focus:ring-emerald-400/20 sm:pr-36 ${
                    correctIndex === index
                      ? "border-emerald-400/60"
                      : "border-slate-700 focus:border-emerald-400"
                  }`}
                  placeholder={`${t("create.questions.option")} ${index + 1}`}
                  value={value}
                  disabled={!!busy}
                  onChange={(event) => {
                    const next = [...opts];
                    next[index] = event.target.value;
                    setOpts(next);
                  }}
                />

                <label className="absolute right-2 top-1/2 inline-flex -translate-y-1/2 items-center gap-2 rounded-md border border-slate-700 bg-slate-950/90 px-2 py-1.5 text-xs text-slate-300">
                  <input
                    type="radio"
                    name={`correct-answer-${groupId}`}
                    className="accent-emerald-400"
                    checked={index === correctIndex}
                    disabled={!!busy}
                    onChange={() => setCorrectIndex(index)}
                  />

                  <span className="hidden sm:inline">
                    {t("create.questions.correct")}
                  </span>
                </label>
              </div>
            ))}
          </div>

          <button
            type="button"
            onClick={add}
            disabled={isFreeLimitReached || !!busy}
            title={
              isFreeLimitReached
                ? t("editor.limit.freeReached", {
                    limit: FREE_QUESTION_LIMIT,
                  })
                : undefined
            }
            className="inline-flex min-h-11 items-center justify-center gap-2 rounded-xl bg-gradient-to-r from-emerald-400 to-cyan-400 px-5 py-2.5 text-sm font-bold text-slate-950 transition hover:brightness-110 disabled:cursor-not-allowed disabled:opacity-40"
          >
            {busy === "add" ? (
              <Loader2 size={18} className="animate-spin" />
            ) : (
              <PlusCircle size={18} />
            )}

            {busy === "add" ? copy.saving : t("editor.addQuestion")}
          </button>

          {isFreeLimitReached && (
            <p className="text-sm text-amber-300">
              {t("editor.limit.freeReached", {
                limit: FREE_QUESTION_LIMIT,
              })}
            </p>
          )}
        </div>
      )}

      {/* Lista de perguntas */}
      {sortedQuestions.length > 0 && (
        <ul className="space-y-3">
          {sortedQuestions.map((question, questionIndex) => (
            <li
              key={question.id}
              className="rounded-xl border border-white/10 bg-[#101b30]/80 p-4 transition hover:border-cyan-400/20"
            >
              <div className="flex items-start justify-between gap-4">
                <div className="min-w-0 flex-1">
                  <h4 className="mb-3 font-semibold leading-relaxed text-slate-100">
                    <span className="mr-2 text-cyan-300">
                      {questionIndex + 1}.
                    </span>

                    {question.text}
                  </h4>

                  <ol className="grid gap-2 sm:grid-cols-2">
                    {question.options?.map((option, optionIndex) => {
                      const isCorrect = optionIndex === question.correctIndex;

                      return (
                        <li
                          key={optionIndex}
                          className={`flex items-start gap-2 rounded-lg border px-3 py-2 text-sm ${
                            isCorrect
                              ? "border-emerald-400/30 bg-emerald-400/10 text-emerald-200"
                              : "border-white/5 bg-slate-950/40 text-slate-300"
                          }`}
                        >
                          <span className="font-semibold opacity-70">
                            {String.fromCharCode(65 + optionIndex)}.
                          </span>

                          <span className="min-w-0 flex-1 break-words">
                            {option}
                          </span>

                          {isCorrect && (
                            <CheckCircle2
                              size={16}
                              className="shrink-0 text-emerald-400"
                              aria-label={copy.correctAnswer}
                            />
                          )}
                        </li>
                      );
                    })}
                  </ol>
                </div>

                {/* Excluir somente enquanto editável */}
                {canEdit && (
                  <button
                    type="button"
                    onClick={() => remove(question.id)}
                    disabled={!!busy}
                    className="flex h-9 w-9 shrink-0 items-center justify-center rounded-lg border border-rose-400/20 bg-rose-400/5 text-rose-400 transition hover:border-rose-400/50 hover:bg-rose-400/10 disabled:opacity-40"
                    title={t("editor.remove")}
                    aria-label={t("editor.remove")}
                  >
                    {busy === question.id ? (
                      <Loader2 size={17} className="animate-spin" />
                    ) : (
                      <Trash2 size={17} />
                    )}
                  </button>
                )}
              </div>
            </li>
          ))}
        </ul>
      )}
    </section>
  );
}
